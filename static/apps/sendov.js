/*
 * sendov.js — DOM-free core for the "Sendov infeasibility" applet.
 *
 * Illustrates that the inequality labelled (stat) in Tao's digestion of the proof of
 * Sendov's conjecture is INFEASIBLE over the range 5 <= n <= 200, 0 <= alpha <= 17,
 * c(alpha)^2 <= a^2.  Concretely, with
 *
 *     a^2   = 1 - 2*alpha/(n-1)
 *     c     = 1 - alpha/(n-1) - alpha/(2*(3+alpha))
 *     I     = \int_0^1 t^3 (1 - 2 c t + a^2 t^2)^{(n-4)/2} dt
 *
 * the right-hand side of (stat) is
 *
 *     R(n,alpha) = 1/6 + 1/(4(3+alpha)) + 1/(2(n-1)) + 1/(4(n-1)(3+alpha))
 *                + a^4 n (n-1)(n-2) / (4(3+alpha)) * I
 *
 * and the claim "(stat) is infeasible" is exactly R(n,alpha) < 1 throughout the region.
 *
 * The integrand has a half-integer exponent for odd n, but Gauss-Legendre quadrature
 * does not care about parity: a single fixed 64-node rule on [0,1] resolves I to ~14
 * digits for every admissible (n,alpha) with n in [5,200] (verified against a 60-digit
 * mpmath reference).  For EVEN n the integral has a polynomial closed form; we also
 * evaluate it exactly with BigInt rationals as a cross-check (the naive expansion is
 * numerically useless in floating point at large n, so this is exact-arithmetic only).
 *
 * No network, no dependencies: the quadrature nodes are generated at load time.
 */
(function (root) {
  "use strict";

  // ---------------------------------------------------------------------------
  // Gauss-Legendre quadrature on [0,1] (nodes generated by Newton's method).
  // ---------------------------------------------------------------------------
  function gaussLegendre(N) {
    const x = new Array(N), w = new Array(N);
    const m = (N + 1) >> 1;
    for (let i = 0; i < m; i++) {
      let z = Math.cos(Math.PI * (i + 0.75) / (N + 0.5)), z1, pp;
      do {
        let p1 = 1, p2 = 0;
        for (let j = 0; j < N; j++) {
          const p3 = p2; p2 = p1;
          p1 = ((2 * j + 1) * z * p2 - j * p3) / (j + 1);
        }
        pp = N * (z * p1 - p2) / (z * z - 1);
        z1 = z; z = z1 - p1 / pp;
      } while (Math.abs(z - z1) > 1e-15);
      x[i] = -z; x[N - 1 - i] = z;
      const ww = 2 / ((1 - z * z) * pp * pp);
      w[i] = ww; w[N - 1 - i] = ww;
    }
    return { t: x.map(v => 0.5 * (v + 1)), w: w.map(v => 0.5 * v) };
  }

  const GL = gaussLegendre(64);

  // ---------------------------------------------------------------------------
  // Basic quantities.
  // ---------------------------------------------------------------------------
  function params(n, alpha) {
    const a2 = 1 - 2 * alpha / (n - 1);
    const c = 1 - alpha / (n - 1) - alpha / (2 * (3 + alpha));
    return { a2: a2, a: Math.sqrt(Math.max(a2, 0)), c: c };
  }

  // Quadratic Q(t) = 1 - 2 c t + a^2 t^2 = beta-like factor inside the integral.
  function qval(t, c, a2) { return 1 - 2 * c * t + a2 * t * t; }

  // The integral I(n,alpha) by 64-node Gauss-Legendre.  Returns NaN if the
  // integrand leaves the reals (Q(t) <= 0 somewhere, i.e. c^2 > a^2 badly).
  function integral(n, alpha) {
    const p = params(n, alpha), pw = (n - 4) / 2;
    let s = 0;
    for (let i = 0; i < GL.t.length; i++) {
      const t = GL.t[i], Q = qval(t, p.c, p.a2);
      if (Q <= 0) return NaN;
      s += GL.w[i] * t * t * t * Math.pow(Q, pw);
    }
    return s;
  }

  // R(n,alpha): the right-hand side of (stat).  The five terms are returned
  // separately too (handy for the "which term dominates" breakdown).
  function terms(n, alpha) {
    const p = params(n, alpha), I = integral(n, alpha), a4 = p.a2 * p.a2;
    const t0 = 1 / 6;
    const t1 = 1 / (4 * (3 + alpha));
    const t2 = 1 / (2 * (n - 1));
    const t3 = 1 / (4 * (n - 1) * (3 + alpha));
    const t4 = a4 * n * (n - 1) * (n - 2) / (4 * (3 + alpha)) * I;
    return { t0: t0, t1: t1, t2: t2, t3: t3, t4: t4, integral: I, sum: t0 + t1 + t2 + t3 + t4 };
  }

  function rhs(n, alpha) { return terms(n, alpha).sum; }

  // ---------------------------------------------------------------------------
  // Admissibility: 0 <= alpha <= 17, a^2 > 0 (i.e. alpha < (n-1)/2), c^2 <= a^2.
  // ---------------------------------------------------------------------------
  const ALPHA_MAX = 17;

  function isAdmissible(n, alpha, tol) {
    if (tol === undefined) tol = 1e-12;
    if (!(alpha >= 0 && alpha <= ALPHA_MAX)) return false;
    const p = params(n, alpha);
    if (!(p.a2 > 0)) return false;
    return p.c * p.c <= p.a2 + tol;
  }

  // Contiguous admissible alpha-interval for a given n (starts at alpha=0, where
  // c=a=1 sits on the boundary).  Returns null if empty.
  function admissibleRange(n) {
    const hi0 = Math.min(ALPHA_MAX, (n - 1) / 2), M = 4000;
    let lo = null, hi = null;
    for (let i = 0; i <= M; i++) {
      const a = hi0 * i / M;
      if (isAdmissible(n, a)) { if (lo === null) lo = a; hi = a; }
    }
    // refine the upper endpoint by bisection between last-admissible and next grid point
    if (hi !== null && hi < hi0) {
      let aOk = hi, aBad = Math.min(hi0, hi + hi0 / M);
      for (let k = 0; k < 40; k++) {
        const mid = 0.5 * (aOk + aBad);
        if (isAdmissible(n, mid)) aOk = mid; else aBad = mid;
      }
      hi = aOk;
    }
    return lo === null ? null : { lo: lo, hi: hi };
  }

  // Maximum of R over the admissible alpha-interval for a given n (coarse scan
  // then a local golden-section polish).  Returns { alpha, R } or null.
  function maxOverAlpha(n) {
    const r = admissibleRange(n);
    if (!r) return null;
    const M = 600;
    let bestA = r.lo, bestR = -Infinity;
    for (let i = 0; i <= M; i++) {
      const a = r.lo + (r.hi - r.lo) * i / M, v = rhs(n, a);
      if (isFinite(v) && v > bestR) { bestR = v; bestA = a; }
    }
    // golden-section polish in a bracket around bestA
    let lo = Math.max(r.lo, bestA - (r.hi - r.lo) / M);
    let hi = Math.min(r.hi, bestA + (r.hi - r.lo) / M);
    const gr = (Math.sqrt(5) - 1) / 2;
    let x1 = hi - gr * (hi - lo), x2 = lo + gr * (hi - lo);
    let f1 = rhs(n, x1), f2 = rhs(n, x2);
    for (let k = 0; k < 60; k++) {
      if (f1 < f2) { lo = x1; x1 = x2; f1 = f2; x2 = lo + gr * (hi - lo); f2 = rhs(n, x2); }
      else { hi = x2; x2 = x1; f2 = f1; x1 = hi - gr * (hi - lo); f1 = rhs(n, x1); }
    }
    const a = 0.5 * (lo + hi), v = rhs(n, a);
    if (v > bestR) { bestR = v; bestA = a; }
    return { alpha: bestA, R: bestR };
  }

  // Global maximum of R over the whole region (integer n in [nMin,nMax]).
  function globalMax(nMin, nMax) {
    nMin = nMin || 5; nMax = nMax || 200;
    let best = { n: null, alpha: null, R: -Infinity };
    for (let n = nMin; n <= nMax; n++) {
      const m = maxOverAlpha(n);
      if (m && m.R > best.R) best = { n: n, alpha: m.alpha, R: m.R };
    }
    return best;
  }

  // ---------------------------------------------------------------------------
  // Exact even-n cross-check via BigInt rationals.
  //   For even n, k = (n-4)/2 is a non-negative integer and Q(t)^k is a polynomial,
  //   so I = \int_0^1 t^3 Q(t)^k dt is an exact rational.  We take the EXACT IEEE
  //   values of a^2 and c (dyadic rationals) so the check compares the very same
  //   integrand the quadrature saw.
  // ---------------------------------------------------------------------------
  function bgcd(a, b) { a = a < 0n ? -a : a; b = b < 0n ? -b : b; while (b) { const t = a % b; a = b; b = t; } return a || 1n; }
  function rmk(n, d) { if (d < 0n) { n = -n; d = -d; } const g = bgcd(n, d); return { n: n / g, d: d / g }; }

  // Exact rational for the IEEE double x (x = n/d with d a power of two).
  function doubleToRat(x) {
    if (x === 0) return { n: 0n, d: 1n };
    const dv = new DataView(new ArrayBuffer(8));
    dv.setFloat64(0, x);
    const hi = dv.getUint32(0), lo = dv.getUint32(4);
    const sign = (hi >>> 31) ? -1n : 1n;
    let exp = (hi >>> 20) & 0x7ff;
    let mant = (BigInt(hi & 0xfffff) << 32n) | BigInt(lo >>> 0);
    if (exp === 0) { exp = 1; } else { mant = mant | (1n << 52n); }
    const e = BigInt(exp - 1023 - 52);
    let num, den;
    if (e >= 0n) { num = sign * mant * (1n << e); den = 1n; }
    else { num = sign * mant; den = 1n << (-e); }
    return rmk(num, den);
  }

  // Rational -> Number, robust to astronomically large exact numerator/denominator.
  function ratToNumber(r) {
    let n = r.n, d = r.d, sign = 1;
    if (n < 0n) { sign = -1; n = -n; }
    if (n === 0n) return 0;
    const P = 96n;
    const q = (n << P) / d;                 // ~ value * 2^96 as an integer
    return sign * Number(q) * Math.pow(2, -96);
  }

  // Integer polynomial multiply (coefficients low -> high, no gcd in the loop).
  function ipolyMul(A, B) {
    const C = new Array(A.length + B.length - 1).fill(0n);
    for (let i = 0; i < A.length; i++) for (let j = 0; j < B.length; j++)
      C[i + j] += A[i] * B[j];
    return C;
  }
  function ipolyPow(A, k) {
    let R = [1n], base = A;
    while (k > 0) { if (k & 1) R = ipolyMul(R, base); k >>= 1; if (k) base = ipolyMul(base, base); }
    return R;
  }

  // Exact even-n integral, { rat, value }, or null for odd n.
  //   Since a^2 and c are dyadic (power-of-two denominators), scale Q by their
  //   common denominator M so Q_int(t) = M*Q(t) has integer coefficients.  Then
  //   Q(t)^k = Q_int(t)^k / M^k with Q_int^k an integer polynomial (integer
  //   polyPow, no gcd), and I = (1/M^k) * sum_i (Q_int^k)_i / (i+4).  A single
  //   reduction at the very end.
  function integralExactEven(n, alpha) {
    if (n % 2 !== 0) return null;
    const k = (n - 4) / 2;
    if (k < 0) return null;
    const p = params(n, alpha);
    const cr = doubleToRat(p.c), ar = doubleToRat(p.a2);
    const M = ar.d > cr.d ? ar.d : cr.d;            // both are powers of two
    const Qint = [M, -2n * cr.n * (M / cr.d), ar.n * (M / ar.d)];
    const P = ipolyPow(Qint, k);                    // integer coeffs, low -> high
    const deg = P.length - 1;
    let Lcd = 1n;                                    // lcm(4 .. deg+4)
    for (let d = 4; d <= deg + 4; d++) { const g = bgcd(Lcd, BigInt(d)); Lcd = Lcd / g * BigInt(d); }
    let num = 0n;
    for (let i = 0; i < P.length; i++) num += P[i] * (Lcd / BigInt(i + 4));
    const den = Lcd * (M ** BigInt(k));
    const rat = rmk(num, den);
    return { rat: rat, value: ratToNumber(rat) };
  }

  // ---------------------------------------------------------------------------
  // Heatmap of R over the (n, alpha) rectangle.  Values at inadmissible cells
  // are set to NaN.  Returns column-major-ish rows (row = alpha, col = n).
  // ---------------------------------------------------------------------------
  function heatmap(opts) {
    opts = opts || {};
    const nMin = opts.nMin || 5, nMax = opts.nMax || 200;
    const aMin = opts.aMin !== undefined ? opts.aMin : 0;
    const aMax = opts.aMax !== undefined ? opts.aMax : ALPHA_MAX;
    const cols = opts.cols || (nMax - nMin + 1);
    const rows = opts.rows || 200;
    const data = new Float64Array(cols * rows);
    let vmax = -Infinity, vmin = Infinity;
    for (let ci = 0; ci < cols; ci++) {
      const n = Math.round(nMin + (nMax - nMin) * (cols === 1 ? 0 : ci / (cols - 1)));
      for (let ri = 0; ri < rows; ri++) {
        const alpha = aMin + (aMax - aMin) * (rows === 1 ? 0 : ri / (rows - 1));
        let v = NaN;
        if (isAdmissible(n, alpha)) { v = rhs(n, alpha); if (!isFinite(v)) v = NaN; }
        data[ri * cols + ci] = v;
        if (isFinite(v)) { if (v > vmax) vmax = v; if (v < vmin) vmin = v; }
      }
    }
    return { data: data, cols: cols, rows: rows, nMin: nMin, nMax: nMax, aMin: aMin, aMax: aMax, vmin: vmin, vmax: vmax };
  }

  const api = {
    ALPHA_MAX: ALPHA_MAX,
    gaussLegendre: gaussLegendre,
    GL: GL,
    params: params,
    qval: qval,
    integral: integral,
    integralExactEven: integralExactEven,
    terms: terms,
    rhs: rhs,
    isAdmissible: isAdmissible,
    admissibleRange: admissibleRange,
    maxOverAlpha: maxOverAlpha,
    globalMax: globalMax,
    heatmap: heatmap,
    // exposed for tests
    doubleToRat: doubleToRat,
    ratToNumber: ratToNumber
  };

  if (typeof module !== "undefined" && module.exports) module.exports = api;
  root.Sendov = api;
})(typeof window !== "undefined" ? window : this);
